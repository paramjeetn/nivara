    tot_cost   = kpis.get("total_cost_inr", 0)
    tot_carbon = kpis.get("total_carbon_tons", 0)
    waste_kwh  = kpis.get("wasted_kwh", 0)
    waste_pct  = kpis.get("waste_pct", 0)
    ann_energy = kpis.get("annual_kwh_projection", 0)
